-- Snapshot explícito de la plantilla validada actual, sin cambiar la tabla jugadores.
insert into public.jugadores_historial (
  user_id,
  jugador_id,
  payload,
  updated_at,
  deleted_at,
  motivo,
  captured_at
)
select
  j.user_id,
  j.id,
  j.payload,
  j.updated_at,
  j.deleted_at,
  'baseline_validada_20260919',
  now()
from public.jugadores j
where j.deleted_at is null
  and not exists (
    select 1
    from public.jugadores_historial h
    where h.user_id=j.user_id
      and h.jugador_id=j.id
      and h.motivo='baseline_validada_20260919'
  );
