-- CampoBase · auditoría defensiva de datos deportivos
-- 19/09/2026
-- Aditiva y no destructiva. No modifica payloads deportivos existentes.

create table if not exists public.campobase_datos_historial (
  audit_id bigint generated by default as identity primary key,
  source_table text not null check (source_table in ('partidos','convocatorias','asistencias','configuracion')),
  user_id uuid not null,
  record_id text not null,
  record jsonb not null,
  motivo text not null,
  captured_at timestamptz not null default now()
);

create index if not exists campobase_datos_historial_user_source_record_idx
  on public.campobase_datos_historial (user_id, source_table, record_id, captured_at desc);

alter table public.campobase_datos_historial enable row level security;

drop policy if exists "campobase_historial_select_own" on public.campobase_datos_historial;
create policy "campobase_historial_select_own"
  on public.campobase_datos_historial
  for select
  using (auth.uid() = user_id);

create or replace function public.auditar_campobase_dato()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.campobase_datos_historial (
    source_table,
    user_id,
    record_id,
    record,
    motivo,
    captured_at
  )
  values (
    TG_TABLE_NAME,
    OLD.user_id,
    OLD.id,
    to_jsonb(OLD),
    lower(TG_OP),
    now()
  );

  if TG_OP = 'DELETE' then
    return OLD;
  end if;
  return NEW;
end;
$$;

drop trigger if exists trg_auditar_partidos on public.partidos;
create trigger trg_auditar_partidos
before update or delete on public.partidos
for each row execute function public.auditar_campobase_dato();

drop trigger if exists trg_auditar_convocatorias on public.convocatorias;
